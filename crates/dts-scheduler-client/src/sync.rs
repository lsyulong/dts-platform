use anyhow::Result;
use tracing::info;

use crate::{client::JiaSchedulerClient, models::*};

// JIA's save endpoints have no atomic upsert-by-name contract.
static SCHEDULE_MUTATIONS: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());

pub struct TaskSync {
    client: JiaSchedulerClient,
    executor_id: u64,
    instance_id: String,
}

impl TaskSync {
    pub async fn new(client: JiaSchedulerClient, instance_id: &str) -> Result<Self> {
        if instance_id.is_empty()
            || instance_id.len() > 128
            || !instance_id
                .chars()
                .all(|ch| ch.is_ascii_alphanumeric() || "-_.:".contains(ch))
        {
            anyhow::bail!("a single explicit JIA_INSTANCE_ID is required");
        }
        client.require_online_instance(instance_id).await?;
        let _guard = SCHEDULE_MUTATIONS.lock().await;
        let executor_id = client.ensure_dts_executor().await?;
        Ok(Self {
            client,
            executor_id,
            instance_id: instance_id.to_owned(),
        })
    }

    /// Returns the EID generated by JIA, after looking it up using its saved database ID.
    pub async fn upsert_job(
        &self,
        task_id: &str,
        task_name: &str,
        start_url: &str,
        dts_service_token: &str,
        cron_expr: Option<&str>,
    ) -> Result<String> {
        let name = Self::job_name(task_id)?;
        let timer_expr = cron_expr.map(TimerExpr::from_cron).transpose()?;
        let _guard = SCHEDULE_MUTATIONS.lock().await;
        let job = self
            .save_task_job(task_id, task_name, start_url, dts_service_token, &name)
            .await?;
        if let Some(expr) = timer_expr {
            self.upsert_timer(task_id, &job.eid, task_name, expr.clone())
                .await?;
            self.activate_schedule(&job.eid, &Self::timer_name(task_id)?, expr)
                .await?;
        }
        info!(
            task_id,
            jia_job_id = job.id,
            "scheduled HTTP trigger dispatched"
        );
        Ok(job.eid)
    }

    async fn save_task_job(
        &self,
        task_id: &str,
        task_name: &str,
        start_url: &str,
        token: &str,
        name: &str,
    ) -> Result<JobRecord> {
        let existing = self.client.find_job(name).await?;
        let req = SaveJobReq {
            name: name.to_owned(),
            code: build_curl_start_command(start_url, token),
            executor_id: self.executor_id,
            info: format!("DTS task: {task_name}"),
            timeout: 60,
            max_retry: 0,
            max_parallel: 1,
            work_dir: String::new(),
            work_user: String::new(),
            id: existing.as_ref().map(|job| job.id),
            args: Vec::new(),
        };
        let saved = self.client.save_job(&req).await?;
        if existing.as_ref().is_some_and(|job| job.id != saved.result) {
            anyhow::bail!("scheduler returned a different job ID during update");
        }
        let job = self.client.job_by_id(saved.result).await?;
        if job.name != name {
            anyhow::bail!("saved scheduler job name does not match task");
        }
        info!(task_id, jia_job_id = saved.result, "scheduler job saved");
        Ok(job)
    }

    async fn activate_schedule(&self, eid: &str, name: &str, expr: TimerExpr) -> Result<()> {
        let endpoint = || DispatchEndpoint {
            instance_id: self.instance_id.clone(),
        };
        if let Some(schedule) = self.client.find_schedule(eid, name).await? {
            self.client
                .schedule_action(schedule.id, "stop_timer")
                .await?;
            let saved = self
                .client
                .save_schedule(&SaveScheduleReq {
                    id: schedule.id,
                    name: name.to_owned(),
                    eid: eid.to_owned(),
                    endpoints: vec![endpoint()],
                    timer_expr: expr.as_custom(),
                    args: Vec::new(),
                })
                .await?;
            if saved.result != schedule.id {
                anyhow::bail!("scheduler updated a different runtime schedule");
            }
            self.client
                .schedule_action(schedule.id, "start_timer")
                .await?;
        } else {
            self.client
                .dispatch(&DispatchJobReq {
                    eid: eid.to_owned(),
                    action: "start_timer".into(),
                    schedule_type: "timer".into(),
                    endpoints: vec![endpoint()],
                    schedule_name: name.to_owned(),
                    is_sync: false,
                    timer_expr: Some(expr),
                    restart_interval: None,
                    args: Some(serde_json::json!([])),
                })
                .await?;
        }
        Ok(())
    }

    async fn upsert_timer(
        &self,
        task_id: &str,
        eid: &str,
        task_name: &str,
        expr: TimerExpr,
    ) -> Result<u64> {
        let name = Self::timer_name(task_id)?;
        let existing = self.client.find_timer(&name).await?;
        if existing.as_ref().is_some_and(|timer| timer.eid != eid) {
            anyhow::bail!("scheduler timer belongs to a different job");
        }
        let req = SaveTimerReq {
            name,
            eid: eid.to_owned(),
            job_type: "default".into(),
            timer_expr: expr,
            job_args: Vec::new(),
            info: format!("DTS task trigger: {task_name}"),
            id: existing.as_ref().map(|timer| timer.id),
        };
        let saved = self.client.save_timer(&req).await?;
        if existing
            .as_ref()
            .is_some_and(|timer| timer.id != saved.result)
        {
            anyhow::bail!("scheduler returned a different timer ID during update");
        }
        Ok(saved.result)
    }

    pub async fn remove_timer(&self, task_id: &str) -> Result<()> {
        Self::remove_task_timer(&self.client, task_id).await
    }

    /// Deleting a schedule does not require or create an executor.
    pub async fn remove_task_timer(client: &JiaSchedulerClient, task_id: &str) -> Result<()> {
        let name = Self::timer_name(task_id)?;
        let _guard = SCHEDULE_MUTATIONS.lock().await;
        let timer = client.find_timer(&name).await?;
        let job = client.find_job(&Self::job_name(task_id)?).await?;
        if let Some(job) = job {
            if timer.as_ref().is_some_and(|timer| timer.eid != job.eid) {
                anyhow::bail!("scheduler timer belongs to a different job");
            }
            if let Some(schedule) = client.find_schedule(&job.eid, &name).await? {
                client.schedule_action(schedule.id, "stop_timer").await?;
            }
        } else if timer.is_some() {
            anyhow::bail!("scheduled task job is missing");
        }
        if let Some(timer) = timer {
            client.delete_timer(timer.id).await?;
        }
        Ok(())
    }

    pub fn timer_name(task_id: &str) -> Result<String> {
        validate_task_id(task_id)?;
        Ok(format!("DTS-Timer-{task_id}"))
    }

    pub fn job_name(task_id: &str) -> Result<String> {
        validate_task_id(task_id)?;
        Ok(format!("[DTS:{task_id}]"))
    }
}

fn validate_task_id(task_id: &str) -> Result<()> {
    if task_id.is_empty()
        || task_id.len() > 36
        || !task_id
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || ch == '-')
    {
        anyhow::bail!("invalid DTS task ID for scheduler");
    }
    Ok(())
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\"'\"'"))
}

fn build_curl_start_command(start_url: &str, token: &str) -> String {
    format!(
        "curl --fail --silent --show-error --max-time 30 -X POST {} -H {}",
        shell_quote(start_url),
        shell_quote(&format!("Authorization: Bearer {token}"))
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn timer_uses_task_identity_and_fits_upstream_name_limit() {
        let task_id = "d0e2e5f0-f60d-4cf1-94eb-ab0448cdc998";
        assert_eq!(
            TaskSync::timer_name(task_id).expect("name"),
            format!("DTS-Timer-{task_id}")
        );
        assert!(TaskSync::job_name(task_id).expect("name").len() <= 50);
        assert!(TaskSync::timer_name("task/../../foreign").is_err());
    }

    #[test]
    fn cron_maps_unix_fields_to_real_jia_timer_dto() {
        let expr = TimerExpr::from_cron("*/5 * * * 1-5").expect("cron");
        assert_eq!(expr.second, "0");
        assert_eq!(expr.minute, "*/5");
        assert_eq!(expr.year, "1-5");
        assert_eq!(expr.to_cron(), "*/5 * * * 1-5");
        assert!(TimerExpr::from_cron("0 0 0 * * * 2026").is_err());
        assert!(TimerExpr::from_cron("").is_err());
    }

    #[test]
    fn curl_command_quotes_url_and_grant_and_fails_on_rejected_start() {
        let cmd = build_curl_start_command(
            "http://platform/start?tenant_id=t&actor_id=u",
            "fixture's-grant",
        );
        assert!(cmd.contains("--fail"));
        assert!(cmd.contains("'http://platform/start?tenant_id=t&actor_id=u'"));
        assert!(cmd.contains("'Authorization: Bearer fixture'\"'\"'s-grant'"));
    }
}
