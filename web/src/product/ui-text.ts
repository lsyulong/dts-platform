export const productText = (language: string) => (language.startsWith('zh') ? zh : en);
export const statusText = (status: string, language: string) => {
  const states: Record<string, [string, string]> = {
    queued: ['排队中', 'Queued'],
    register: ['登记资产', 'Register asset'],
    registered: ['已登记', 'Registered'],
    issue_credential: ['签发凭据', 'Issue credential'],
    revoke_credential: ['撤销凭据', 'Revoke credential'],
    cancelled: ['已取消', 'Cancelled'],
    skipped: ['依赖失败，已跳过', 'Skipped'],
    reconciliation_required: ['待核对执行结果', 'Reconciliation required'],
    allocate: ['分配编码', 'Allocate code'],
    revoke: ['撤销授权', 'Revoke grant'],
    revoked: ['授权已撤销', 'Grant revoked'],
    withdrawn: ['已撤回', 'Withdrawn'],
    missing: ['源端缺失', 'Missing at source'],
    passed: ['校验通过', 'Passed'],
    empty_data: ['没有可校验数据', 'No data to check'],
    denied: ['拒绝访问', 'Access denied'],
    not_registered: ['未注册', 'Not registered'],
    registering: ['注册中', 'Registering'],
    registration_unknown: ['注册结果待核对', 'Registration requires reconciliation'],
    stopping: ['停用中', 'Stopping'],
    stopped: ['已停用计划', 'Schedule stopped'],
    stop_unknown: ['停用结果待核对', 'Stop requires reconciliation'],
    query: ['查询访问', 'Query access'],
  };
  if (states[status]) return states[status][language.startsWith('zh') ? 0 : 1];
  const text = productText(language);
  return status in text ? text[status as keyof typeof text] : status;
};
